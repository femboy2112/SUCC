"""Exact Bruhat--Tits balls and source-typed arithmetic boundary charts.

This is geometry, not a claim of gravitational dynamics.  A radius-r sphere is
P^1(Z/p^r), represented by primitive vectors modulo unit rescaling.  Vertices
are the homothety classes of their inverse-image lattices.  All calculations
are integral/rational; no picture is being used to certify adjacency.
"""
from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction
from math import gcd

from .unit_prime_succ import prime
from .pontryagin_source_duality import FiniteCyclicCharacter


class PadicGeometryError(ValueError):
    """An invalid local place, source, chart, or unlicensed inference."""


def _integer(x: int, name: str) -> int:
    if type(x) is not int:
        raise PadicGeometryError(f"{name} must be an exact integer")
    return x


def _place(p: int) -> int:
    if not prime(p):
        raise PadicGeometryError("A Bruhat--Tits place requires a genuine prime")
    return p


def _depth(depth: int) -> int:
    if type(depth) is not int or not 0 <= depth <= 30:
        raise PadicGeometryError("Depth must be an integer in 0..30")
    return depth


@dataclass(frozen=True, order=True)
class BTVertex:
    """Normalized lattice class at a fixed distance from [Z_p^2].

    affine a means the line generated by (a,1) modulo p^depth;
    infinity b means the line generated by (1,p*b).  The second chart
    contains only nonunits in its second coordinate, so the charts are disjoint.
    """

    p: int
    depth: int
    chart: str
    value: int = 0

    def __post_init__(self) -> None:
        _place(self.p)
        _depth(self.depth)
        _integer(self.value, "Projective coordinate")
        if self.depth == 0:
            valid = self.chart == "root" and self.value == 0
        elif self.chart == "affine":
            valid = 0 <= self.value < self.p ** self.depth
        elif self.chart == "infinity":
            valid = 0 <= self.value < self.p ** (self.depth - 1)
        else:
            valid = False
        if not valid:
            raise PadicGeometryError("Noncanonical projective lattice representative")

    @property
    def primitive_vector(self) -> tuple[int, int]:
        if self.depth == 0:
            raise PadicGeometryError("The root is a lattice, not a projective direction")
        return (self.value, 1) if self.chart == "affine" else (1, self.p * self.value)

    @property
    def lattice_basis(self) -> tuple[tuple[int, int], tuple[int, int]]:
        """Columns of an integral basis for the Z_p inverse-image lattice."""
        if self.depth == 0:
            return ((1, 0), (0, 1))
        q = self.p ** self.depth
        return ((q, 0), (self.value, 1)) if self.chart == "affine" else ((1, self.p * self.value), (0, q))

    def contains_integral(self, x: int, y: int) -> bool:
        """Exact membership for integral test vectors; coefficients extend to Z_p."""
        _integer(x, "First lattice coordinate")
        _integer(y, "Second lattice coordinate")
        if self.depth == 0:
            return True
        q = self.p ** self.depth
        return (x - self.value * y) % q == 0 if self.chart == "affine" else (y - self.p * self.value * x) % q == 0

    def reduce(self, depth: int) -> "BTVertex":
        _depth(depth)
        if depth > self.depth:
            raise PadicGeometryError("Reduction cannot invent a finer direction")
        if depth == 0:
            return BTVertex(self.p, 0, "root")
        modulus = self.p ** (depth if self.chart == "affine" else depth - 1)
        return BTVertex(self.p, depth, self.chart, self.value % modulus)

    def parent(self) -> "BTVertex":
        if self.depth == 0:
            raise PadicGeometryError("The rooted ball gives the root no parent")
        return self.reduce(self.depth - 1)

    def children(self) -> tuple["BTVertex", ...]:
        if self.depth == 0:
            return bt_sphere(self.p, 1)
        step = self.p ** (self.depth if self.chart == "affine" else self.depth - 1)
        return tuple(BTVertex(self.p, self.depth + 1, self.chart, self.value + j * step) for j in range(self.p))

    def gl2_action(self, matrix: tuple[tuple[int, int], tuple[int, int]]) -> "BTVertex":
        """Root-preserving GL_2(Z_p) action from an integral matrix of unit determinant."""
        if (type(matrix) is not tuple or len(matrix) != 2 or
                any(type(row) is not tuple or len(row) != 2 for row in matrix)):
            raise PadicGeometryError("An exact 2 by 2 integral matrix is required")
        a, b = matrix[0]
        c, d = matrix[1]
        for x in (a, b, c, d):
            _integer(x, "Matrix coefficient")
        if (a * d - b * c) % self.p == 0:
            raise PadicGeometryError("Nonunit determinant does not preserve the rooted sphere")
        if self.depth == 0:
            return self
        x, y = self.primitive_vector
        return projective_vertex(self.p, self.depth, a * x + b * y, c * x + d * y)


def projective_vertex(p: int, depth: int, x: int, y: int) -> BTVertex:
    """Normalize a primitive pair modulo p^depth, invariant under unit rescaling."""
    _place(p)
    _depth(depth)
    _integer(x, "First projective coordinate")
    _integer(y, "Second projective coordinate")
    if depth == 0 or (x % p == 0 and y % p == 0):
        raise PadicGeometryError("A positive-depth primitive projective pair is required")
    q = p ** depth
    if y % p:
        return BTVertex(p, depth, "affine", (x * pow(y, -1, q)) % q)
    return BTVertex(p, depth, "infinity", ((y * pow(x, -1, q)) % q) // p)


def bt_sphere(p: int, depth: int) -> tuple[BTVertex, ...]:
    _place(p)
    _depth(depth)
    if depth == 0:
        return (BTVertex(p, 0, "root"),)
    if (p + 1) * p ** (depth - 1) > 4096:
        raise PadicGeometryError("Executable sphere exceeds 4096 vertices")
    return tuple(BTVertex(p, depth, "affine", a) for a in range(p ** depth)) + tuple(
        BTVertex(p, depth, "infinity", b) for b in range(p ** (depth - 1)))


@dataclass(frozen=True)
class BTBall:
    p: int
    radius: int
    vertices: tuple[BTVertex, ...]
    edges: tuple[tuple[BTVertex, BTVertex], ...]
    boundary: tuple[BTVertex, ...]

    def neighbors(self, vertex: BTVertex) -> tuple[BTVertex, ...]:
        if vertex not in self.vertices:
            raise PadicGeometryError("Vertex belongs to a different ball")
        return tuple(b if a == vertex else a for a, b in self.edges if a == vertex or b == vertex)


def bruhat_tits_ball(p: int, radius: int) -> BTBall:
    """Induced ball in the lattice-homothety tree, with truncation boundary explicit."""
    _place(p)
    _depth(radius)
    spheres = tuple(bt_sphere(p, d) for d in range(radius + 1))
    vertices = tuple(v for sphere in spheres for v in sphere)
    return BTBall(p, radius, vertices, tuple((v.parent(), v) for v in vertices if v.depth), spheres[-1])


def common_depth(left: BTVertex, right: BTVertex) -> int:
    if left.p != right.p:
        raise PadicGeometryError("No common local tree for different prime places")
    for r in range(min(left.depth, right.depth), -1, -1):
        if left.reduce(r) == right.reduce(r):
            return r
    raise AssertionError("Same-place vertices always share the root")


def tree_distance(left: BTVertex, right: BTVertex) -> int:
    return left.depth + right.depth - 2 * common_depth(left, right)


def boundary_visual_distance(left: BTVertex, right: BTVertex) -> Fraction:
    """Exact cylinder ultrametric on ONE finite sphere, not graph-edge distance."""
    if left.depth != right.depth or left.p != right.p:
        raise PadicGeometryError("One prime and one boundary cutoff are required")
    if left == right:
        return Fraction(0)
    return Fraction(1, left.p ** common_depth(left, right))


def projective_contact_depth(left: BTVertex, right: BTVertex) -> int:
    """Common-prefix depth from the p-adic valuation of a 2 by 2 determinant.

    This independent arithmetic formula does not traverse parent pointers.
    Both inputs must be on the same positive-depth sphere; result is capped
    at the cutoff, so equal cylinders have contact depth equal to that cutoff.
    """
    if left.p != right.p or left.depth != right.depth or left.depth == 0:
        raise PadicGeometryError("One positive-depth projective boundary sphere is required")
    x, y = left.primitive_vector
    z, w = right.primitive_vector
    determinant = x*w - y*z
    count = 0
    while count < left.depth and determinant % left.p == 0:
        determinant //= left.p
        count += 1
    return count


def reconstruct_boundary_clusters(p: int, radius: int) -> tuple[tuple[frozenset[int], ...], ...]:
    """Recover all vertices from determinant contacts on the finest boundary.

    The output at level r partitions boundary indices into contact>=r classes.
    Inclusion of adjacent-level clusters reconstructs the original rooted ball;
    no parent pointers are read in this calculation.
    """
    leaves = bt_sphere(p, radius)
    if radius == 0:
        return ((frozenset((0,)),),)
    levels = []
    for r in range(radius + 1):
        remaining = set(range(len(leaves)))
        clusters = []
        while remaining:
            anchor = min(remaining)
            cluster = frozenset(j for j in remaining if projective_contact_depth(leaves[anchor], leaves[j]) >= r)
            clusters.append(cluster)
            remaining.difference_update(cluster)
        levels.append(tuple(clusters))
    return tuple(levels)


@dataclass(frozen=True)
class ArithmeticBoundaryChart:
    """The genuine affine Z/p^r chart of the projective boundary sphere."""

    p: int
    depth: int
    source_id: str = "Z-integer-modular-source"
    epoch: int = 0

    def __post_init__(self) -> None:
        _place(self.p)
        _depth(self.depth)
        if self.depth == 0:
            raise PadicGeometryError("Arithmetic boundary characters require positive depth")
        if type(self.source_id) is not str or not self.source_id.strip():
            raise PadicGeometryError("A declared source identifier is required")
        if type(self.epoch) is not int or self.epoch < 0:
            raise PadicGeometryError("A nonnegative exact source epoch is required")

    @property
    def modulus(self) -> int:
        return self.p ** self.depth

    def observe_integer(self, n: int) -> BTVertex:
        return BTVertex(self.p, self.depth, "affine", _integer(n, "Source integer") % self.modulus)

    def character(self, label: int) -> FiniteCyclicCharacter:
        return FiniteCyclicCharacter(self.modulus, label, self.source_id, self.epoch)

    def refinement_receipt(self, fine: "ArithmeticBoundaryChart", n: int, label: int) -> dict:
        if ((self.p, self.source_id, self.epoch) != (fine.p, fine.source_id, fine.epoch)
                or fine.depth < self.depth):
            raise PadicGeometryError("Refinement requires the same source, epoch, and prime")
        coarse_vertex = self.observe_integer(n)
        refined_vertex = fine.observe_integer(n)
        phase = self.character(label).naturality(n, fine.modulus)
        if refined_vertex.reduce(self.depth) != coarse_vertex:
            raise AssertionError("Arithmetic observation failed geometric refinement")
        return {"geometric_reduction": True, "character_naturality": phase,
                "source_id": self.source_id, "epoch": self.epoch}


def prime_dilation_embedding(p: int, depth: int) -> tuple[int, ...]:
    """Basis injection C^(p^r) -> C^(p^(r+1)), |a> -> |pa>.

    This lives on consecutive AFFINE boundary charts. It is not a permutation
    of a fixed sphere, and does not claim to be the restriction of V_p on all
    of l2(N) to a coherent residue quotient.
    """
    chart = ArithmeticBoundaryChart(p, depth)
    if chart.modulus > 4096:
        raise PadicGeometryError("Executable affine chart exceeds 4096 basis vectors")
    return tuple(p * a for a in range(chart.modulus))


def residue_measurement_weights(weights: dict[int, Fraction], modulus: int) -> tuple[Fraction, ...]:
    """Classical output of measuring a finite diagonal arithmetic density.

    A legitimate CPTP measurement, not the unbounded coherent residue sum.
    The input must be a normalized finite distribution on positive integers.
    """
    _integer(modulus, "Residue modulus")
    if not 1 <= modulus <= 4096 or type(weights) is not dict:
        raise PadicGeometryError("A finite typed measurement chart is required")
    if any(type(n) is not int or n < 1 or type(w) not in (int, Fraction) or w < 0
           for n, w in weights.items()) or sum(weights.values(), Fraction()) != 1:
        raise PadicGeometryError("Positive integer labels and normalized exact weights are required")
    out = [Fraction(0)] * modulus
    for n, w in weights.items():
        out[n % modulus] += w
    return tuple(out)


def crt_glue(charts: tuple[ArithmeticBoundaryChart, ...], residues: tuple[int, ...]) -> tuple[int, int]:
    """Same-source local affine cylinders glue to one class modulo their product.

    Repeated primes are rejected: nested constraints need explicit reduction
    checks, not a coprime CRT assertion. Finite CRT does not imply an adelic
    gravitational or Archimedean reconstruction theorem.
    """
    if not charts or len(charts) != len(residues):
        raise PadicGeometryError("A nonempty matching local family is required")
    if len({(c.source_id, c.epoch) for c in charts}) != 1:
        raise PadicGeometryError("Cannot glue different original sources or epochs")
    x, modulus = 0, 1
    for chart, residue in zip(charts, residues):
        _integer(residue, "Local residue")
        q = chart.modulus
        if gcd(modulus, q) != 1:
            raise PadicGeometryError("This CRT interface requires distinct prime places")
        x += modulus * (((residue - x) * pow(modulus, -1, q)) % q)
        modulus *= q
        x %= modulus
    return x, modulus
