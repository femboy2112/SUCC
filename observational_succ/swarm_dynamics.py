"""Exact, source-relative factor and closure certificates for swarm D25--D32.

The complete finite source tables are mathematical inputs. Source identifiers
do not authenticate a physical instrument. No floating arithmetic, estimated
chaotic invariant measure, PDE solution, or spacetime validation occurs here.
"""
from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction as F
from typing import Hashable, Sequence


class DynamicsError(ValueError):
    pass


def rational(value: int | F) -> F:
    if isinstance(value, bool) or not isinstance(value, (int, F)):
        raise DynamicsError("Exact integer/Fraction required")
    return F(value)


def natural(value: int, name: str = "count") -> int:
    if type(value) is not int or value < 0:
        raise DynamicsError(f"Nonnegative integer {name} required")
    return value


def _reports(values: Sequence[Hashable]) -> tuple[Hashable, ...]:
    values = tuple(values)
    if not values:
        raise DynamicsError("Nonempty complete finite source required")
    for value in values:
        if not isinstance(value, (int, str, tuple)) or isinstance(value, bool):
            raise DynamicsError("Exact hashable report labels required")
        try:
            hash(value)
        except TypeError as ex:
            raise DynamicsError("Hashable report labels required") from ex
    return values


def _metadata(source_id: str, basis_id: str, version: int) -> None:
    if not isinstance(source_id, str) or not source_id:
        raise DynamicsError("Original source identity required")
    if not isinstance(basis_id, str) or not basis_id:
        raise DynamicsError("Observation basis required")
    natural(version, "source version")


@dataclass(frozen=True)
class FiniteDynamics:
    """States are 0..N-1; a total stationary update and one fixed readout."""
    source_id: str
    basis_id: str
    version: int
    successor: tuple[int, ...]
    reports: tuple[Hashable, ...]

    def __post_init__(self) -> None:
        _metadata(self.source_id, self.basis_id, self.version)
        reports = _reports(self.reports)
        successor = tuple(self.successor)
        if len(successor) != len(reports) or any(
            type(s) is not int or not 0 <= s < len(reports) for s in successor
        ):
            raise DynamicsError("Total successor on the declared finite carrier required")
        object.__setattr__(self, "successor", successor)
        object.__setattr__(self, "reports", reports)

    def delays(self, state: int, length: int) -> tuple[Hashable, ...]:
        natural(length, "delay length")
        if type(state) is not int or not 0 <= state < len(self.reports):
            raise DynamicsError("State outside source carrier")
        result = []
        for _ in range(length):
            result.append(self.reports[state])
            state = self.successor[state]
        return tuple(result)

    def deterministic_factor(self) -> dict:
        """Criterion ker(q) is an update congruence; return a minimal witness."""
        representatives: dict[Hashable, int] = {}
        factor: dict[Hashable, Hashable] = {}
        for state, report in enumerate(self.reports):
            next_report = self.reports[self.successor[state]]
            if report in factor and factor[report] != next_report:
                other = representatives[report]
                return {"valid": False, "witness_states": (other, state),
                        "same_report": report,
                        "distinct_next_reports": (factor[report], next_report)}
            representatives[report] = state
            factor[report] = next_report
        return {"valid": True, "factor": factor}

    def delay_quotient(self, length: int | None = None) -> dict:
        """N-1 delays suffice for the full future behavioral quotient.

        This is a finite-source theorem. A claim that an unknown physical
        carrier has exactly these N states is not generated by the routine.
        """
        if length is None:
            length = len(self.reports)-1
        natural(length, "delay length")
        words = tuple(self.delays(s, length) for s in range(len(self.reports)))
        refined = FiniteDynamics(self.source_id, f"delay:{length}:{self.basis_id}",
                                 self.version, self.successor, words)
        certificate = refined.deterministic_factor()
        return {"length": length, "words": words,
                "injective": len(set(words)) == len(words),
                "closed": certificate["valid"], "factor_certificate": certificate}


def _law(values: Sequence[int | F], size: int) -> tuple[F, ...]:
    values = tuple(rational(x) for x in values)
    if len(values) != size or any(x < 0 for x in values) or sum(values, F(0)) != 1:
        raise DynamicsError("Normalized nonnegative law on the exact carrier required")
    return values


def tv(first: Sequence[int | F], second: Sequence[int | F]) -> F:
    first, second = tuple(map(rational, first)), tuple(map(rational, second))
    if len(first) != len(second):
        raise DynamicsError("Common probability basis required")
    _law(first, len(first))
    _law(second, len(second))
    return sum((abs(x-y) for x, y in zip(first, second)), F(0))/2


@dataclass(frozen=True)
class FiniteStochasticDynamics:
    """Complete stationary hidden-state Markov source with deterministic reports."""
    source_id: str
    basis_id: str
    version: int
    rows: tuple[tuple[F, ...], ...]
    reports: tuple[Hashable, ...]

    def __post_init__(self) -> None:
        _metadata(self.source_id, self.basis_id, self.version)
        reports = _reports(self.reports)
        rows = tuple(_law(row, len(reports)) for row in self.rows)
        if len(rows) != len(reports):
            raise DynamicsError("One transition law for every hidden source state required")
        object.__setattr__(self, "rows", rows)
        object.__setattr__(self, "reports", reports)

    @property
    def labels(self) -> tuple[Hashable, ...]:
        return tuple(dict.fromkeys(self.reports))

    def project_law(self, law: Sequence[int | F]) -> tuple[F, ...]:
        law = _law(law, len(self.reports))
        return tuple(sum((mass for mass, r in zip(law, self.reports) if r == label), F(0))
                     for label in self.labels)

    def projected_rows(self) -> tuple[tuple[F, ...], ...]:
        return tuple(self.project_law(row) for row in self.rows)

    def closure(self, candidate: Sequence[Sequence[int | F]] | None = None) -> dict:
        """Strong lumpability, or a certified defect for one candidate kernel.

        Default candidate averages rows uniformly within each report fiber.
        This is a declared mathematical reference kernel, not a posterior,
        optimal minimax kernel, stationary physical prior, or fit estimate.
        """
        projected = self.projected_rows()
        if candidate is None:
            candidate = tuple(
                tuple(sum((projected[s][j] for s, r in enumerate(self.reports) if r == label), F(0))
                      /self.reports.count(label) for j in range(len(self.labels)))
                for label in self.labels)
        candidate = tuple(_law(row, len(self.labels)) for row in candidate)
        if len(candidate) != len(self.labels):
            raise DynamicsError("Observed kernel must use the full declared report alphabet")
        index = {label: i for i, label in enumerate(self.labels)}
        defects = tuple(tv(row, candidate[index[self.reports[s]]])
                        for s, row in enumerate(projected))
        witness = next(((a, b) for a in range(len(self.reports))
                        for b in range(a+1, len(self.reports))
                        if self.reports[a] == self.reports[b] and projected[a] != projected[b]), None)
        return {"strongly_lumpable": witness is None, "witness_states": witness,
                "kernel": candidate, "projected_rows": projected,
                "defects": defects, "delta": max(defects)}

    def horizon_comparison(self, initial: Sequence[int | F], steps: int,
                           candidate: Sequence[Sequence[int | F]] | None = None) -> dict:
        """Observed marginal versus candidate chain; TV <= min(1,n*delta)."""
        natural(steps, "horizon")
        source = _law(initial, len(self.reports))
        closure = self.closure(candidate)
        kernel = closure["kernel"]
        observed = self.project_law(source)
        for _ in range(steps):
            source = tuple(sum((mass*self.rows[s][j] for s, mass in enumerate(source)), F(0))
                           for j in range(len(source)))
            observed = tuple(sum((mass*kernel[i][j] for i, mass in enumerate(observed)), F(0))
                             for j in range(len(observed)))
        actual = self.project_law(source)
        return {"actual": actual, "candidate": observed, "tv": tv(actual, observed),
                "delta": closure["delta"], "bound": min(F(1), steps*closure["delta"])}


def stochastic_phase_source(bias: int | F = F(1, 2)) -> FiniteStochasticDynamics:
    """Declared symbolic A/B/C PCF source; weights are not a logistic acim."""
    bias = rational(bias)
    if not 0 <= bias <= 1:
        raise DynamicsError("Branch probability must be in [0,1]")
    return FiniteStochasticDynamics("pcf-symbolic-parry-family", "two-phase", 0,
                                   ((0, 0, 1), (0, 0, 1), (bias, 1-bias, 0)), (0, 0, 1))


def noisy_latent_source(error: int | F = F(1, 4)) -> FiniteStochasticDynamics:
    """Fixed hidden bit, freshly corrupted report; source=(latent,report)."""
    error = rational(error)
    if not 0 <= error <= 1:
        raise DynamicsError("Observation error probability must be in [0,1]")
    return FiniteStochasticDynamics("latent-bit-emission", "visible-emission", 0,
        ((1-error, error, 0, 0), (1-error, error, 0, 0),
         (0, 0, error, 1-error), (0, 0, error, 1-error)), (0, 1, 0, 1))


def tent_cylinder(word: Sequence[int]) -> tuple[F, F]:
    """Independent exact inverse-branch construction, closed endpoint convention."""
    word = tuple(word)
    if any(type(bit) is not int or bit not in (0, 1) for bit in word):
        raise DynamicsError("Binary chronological word required")
    low, high = F(0), F(1)
    for bit in reversed(word):
        branch = (lambda x: x/2) if bit == 0 else (lambda x: 1-x/2)
        low, high = sorted((branch(low), branch(high)))
    return low, high


def tent_uncertainty(word: Sequence[int], steps: int) -> dict:
    """Exact image of a closed full-tent cylinder, not generic logistic r."""
    natural(steps, "horizon")
    word = tuple(word)
    initial = tent_cylinder(word)
    final = tent_cylinder(word[steps:])
    return {"initial": initial, "final": final,
            "initial_diameter": initial[1]-initial[0],
            "final_diameter": final[1]-final[0],
            "amplification": 1 << min(steps, len(word))}


def window_transport(word: Sequence[int], width: int, steps: int) -> tuple[int, ...]:
    """k-step future m-word requires supplied m+k original symbols."""
    natural(width, "window width")
    natural(steps, "source steps")
    word = tuple(word)
    tent_cylinder(word)  # validate the exact binary language
    if len(word) < width+steps:
        raise DynamicsError("Unobserved future symbols cannot be manufactured")
    return word[steps:steps+width]


def les_fourier_counterexample(frequency: int = 3) -> dict:
    """Smooth divergence-free T^2 field with invisible velocity, visible force.

    P retains Fourier modes |k| <= 1. Let a=(1,-N), b=(1,-(N-1))
    and w=a*cos((N,1).x)+b*cos((N-1,1).x). Both original modes
    are removed, but their difference (1,0) is retained in w tensor w.
    The exact sin(x) coefficient in Leray(div(P(w tensor w))) is
    (0,(2N-1)/2); it survives pressure elimination.
    """
    if type(frequency) is not int or frequency < 2:
        raise DynamicsError("Integer high frequency N>=2 required")
    n = frequency
    a, b = (F(1), F(-n)), (F(1), F(1-n))
    difference_stress = tuple(tuple((a[i]*b[j]+b[i]*a[j])/2 for j in range(2))
                              for i in range(2))
    constant_stress = tuple(tuple((a[i]*a[j]+b[i]*b[j])/2 for j in range(2))
                            for i in range(2))
    divergence = tuple(-difference_stress[i][0] for i in range(2))
    return {"modes": ((n, 1), (n-1, 1)), "amplitudes": (a, b),
            "filter_radius": 1, "projected_velocity": (F(0), F(0)),
            "constant_stress": constant_stress, "cos_x_stress": difference_stress,
            "sin_x_divergence": divergence,
            "sin_x_leray_divergence": (F(0), divergence[1]),
            "source_is_smooth_divergence_free": True,
            "NS_global_regularity_claimed": False}


def causal_past(event: Sequence[int | F], observer: Sequence[int | F]) -> bool:
    if len(event) != 2 or len(observer) != 2:
        raise DynamicsError("1+1 events require time and space")
    t, x = map(rational, event)
    p, y = map(rational, observer)
    return p-t >= abs(y-x)


def boost(event: Sequence[int | F], half_rapidity: int | F) -> tuple[F, F]:
    """Proper orthochronous rational 1+1 Lorentz boost, c=1."""
    if len(event) != 2:
        raise DynamicsError("1+1 event required")
    t, x = map(rational, event)
    u = rational(half_rapidity)
    if abs(u) >= 1:
        raise DynamicsError("Half-rapidity rational parameter must have |u|<1")
    gamma, gamma_v = (1+u*u)/(1-u*u), 2*u/(1-u*u)
    return gamma*t-gamma_v*x, gamma*x-gamma_v*t


def decode_delays(words: Sequence[Sequence[Hashable]], received: Sequence[Hashable],
                  errors: int) -> dict:
    """Exact finite adversarial Hamming-noise decoder, no empirical noise model."""
    natural(errors, "error budget")
    words, received = tuple(map(tuple, words)), tuple(received)
    if not words or any(len(w) != len(received) for w in words):
        raise DynamicsError("Nonempty common delay coordinate basis required")
    distance = lambda a, b: sum(x != y for x, y in zip(a, b))
    candidates = tuple(i for i, word in enumerate(words) if distance(word, received) <= errors)
    minimum = min((distance(a, b) for i, a in enumerate(words) for b in words[i+1:]),
                  default=None)
    return {"candidates": candidates, "unique": len(candidates) == 1,
            "minimum_distance": minimum,
            "uniform_error_correction_certified": minimum is None or 2*errors < minimum}
