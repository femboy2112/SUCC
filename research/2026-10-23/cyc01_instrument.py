"""
CYC-01 numerical instrument  (Instrument A: exact-integer phase reduction + long-double trig,
                              and rational-orbit path: exact residues + mpmath dps 50).

CYC-01:  |A_{h,N}(x)| <= (R-1)/N + sqrt( 1/R + (R-1)/(2R)*eta_N
                                         + (2/R^2) * sum_{d=1}^{R-1} (R-d) d_{|h|(b^d-1)}(N)
                                         + 2(R-1)(R-2)/(3 R N) )

Conventions / judgment calls (flagged in the report):
  * "genuine primes dividing n" = the distinct primes p | n (sympy.factorint keys).
  * d_n(N) is memoised over the divisor-closed set generated by n_d = |h|(b^d-1), d=1..R-1.
  * Negative h: |A_{-h}| computed from the signed sine (A_{-h}=conj A_h); RHS uses |h| (as in CYC-01).
  * Random x: x = 0.b1b2b3... with iid fair bits from numpy PCG64 (SeedSequence([SEED,k])), the SAME x for
    base 2 (digit = bit) and base 16 (digit = 4 bits).  frac(b^j x) is represented by a 128-bit window
    (truncation error < 2^-128 per phase before multiplication by n; n < 2^32 enforced).
"""
