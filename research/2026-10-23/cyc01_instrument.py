import mpmath as mp
from sympy import factorint, divisors

LD = np.longdouble
assert np.finfo(LD).nmant == 63, "need 80-bit long double"
mp.mp.dps = 50                                   # rational/mp path precision (STATED)
TWO_PI_L = LD(str(mp.nstr(2 * mp.pi, 40)))
TWO_M64 = LD(2) ** -64
U32 = np.uint64(0xFFFFFFFF)
SEED = 20261023

# ----------------------------------------------------------------------------- number theory helpers
_fcache = {}
def primes_of(m):
    if m not in _fcache:
        _fcache[m] = sorted(factorint(m).keys())
    return _fcache[m]

_dcache = {}
def divs(m):
    if m not in _dcache:
        _dcache[m] = divisors(m)
    return _dcache[m]

def needed_set(b, h, Rmax):
    """divisor-closed set generated by n_d=|h|(b^d-1), d=1..Rmax-1 (plus 1)."""
    S = {1}
    for d in range(1, Rmax):
        S.update(divs(abs(h) * (b ** d - 1)))
    return sorted(S)

# ----------------------------------------------------------------------------- d_n recursion (generic arithmetic)
def compute_D(C, needed):
    """C[m] = list (over checkpoints) of c_m(N).  Returns D[m] list, D[1]=0.
       d_m = min_{p | m prime} ( d_{m/p} + |c_m - c_{m/p}| )."""
    K = len(C[1])
    zero = C[1][0] * 0
    D = {1: [zero] * K}
    for m in needed:
        if m == 1:
            continue
        best = None
        for p in primes_of(m):
            q = m // p
            cand = [D[q][i] + abs(C[m][i] - C[q][i]) for i in range(K)]
            best = cand if best is None else [min(a, c) for a, c in zip(best, cand)]
        D[m] = best
    return D

def terms(mk, sqrt, b, h, R, N, c1, Dlist, absA):
    """Return dict of all pieces for ONE (b,h,R,N).  Dlist: dict d-> d_{|h|(b^d-1)}(N) value."""
    eta = max(mk(0), 2 * c1)
    S = sum((R - d) * Dlist[d] for d in range(1, R)) if R > 1 else mk(0)
    T1 = mk(1) / R
    T2 = mk(R - 1) / (2 * R) * eta
    T3 = mk(2) / (R * R) * S
    T4 = mk(2 * (R - 1) * (R - 2)) / (3 * R * N)
    lead = mk(R - 1) / N
    arg = T1 + T2 + T3 + T4
    rhs = lead + sqrt(arg)
    return dict(absA=absA, eta=eta, S=S, T1=T1, T2=T2, T3=T3, T4=T4, lead=lead, arg=arg, RHS=rhs, GAP=rhs - absA)

# ----------------------------------------------------------------------------- Source: bit-window (numpy, long double)
def bits_from_int(M, nbits):
    s = format(M, '0%db' % nbits)
    return np.frombuffer(s.encode(), dtype=np.uint8) - 48

def random_bits(k, nbits):
    rng = np.random.default_rng(np.random.SeedSequence([SEED, k]))
    nbytes = (nbits + 7) // 8
    return np.unpackbits(np.frombuffer(rng.bytes(nbytes), dtype=np.uint8))[:nbits]

class BitSource:
    """x = 0.bits (binary).  base b=2^s; orbit window j starts at bit s*j; 128-bit window."""
    def __init__(self, bits, s, Ns, label):
        self.label, self.s, self.Ns = label, s, list(Ns)
        Nmax = max(Ns)
        assert len(bits) >= s * (Nmax - 1) + 128, "not enough bits"
        idx = s * np.arange(Nmax)
        hi = np.zeros(Nmax, dtype=np.uint64); lo = np.zeros(Nmax, dtype=np.uint64)
        for k in range(64):
            hi |= bits[idx + k].astype(np.uint64) << np.uint64(63 - k)
            lo |= bits[idx + 64 + k].astype(np.uint64) << np.uint64(63 - k)
        self.hi, self.lo = hi, lo
        self._c = {}
    def _theta(self, n):
        assert 0 < n < 2 ** 32, "n out of uint64-limb range: %d" % n
        n = np.uint64(n)
        lo_hi = self.lo >> np.uint64(32); lo_lo = self.lo & U32
        carry = (n * lo_hi + ((n * lo_lo) >> np.uint64(32))) >> np.uint64(32)
        top = n * self.hi + carry          # wraps mod 2^64 : exact fractional part of n*window to 64 bits
        return top.astype(LD) * TWO_M64     # exact conversion (64-bit mantissa)
    def _prefix(self, vals):
        """prefix sums at the checkpoints: pairwise np.sum on each segment between checkpoints, segment totals added
        in order (np.cumsum in long double accumulates ~N*5e-20 systematic error on the MEAN -- observed 4.4e-17 at N=4096;
        replaced; see calibration C3f)."""
        out, acc, a = [], LD(0), 0
        for N in self.Ns:
            acc = acc + np.sum(vals[a:N]); a = N; out.append(acc)
        return out
    def c(self, n):
        if n not in self._c:
            th = self._theta(n)
            pre = self._prefix(np.cos(TWO_PI_L * th))
            self._c[n] = [t / N for t, N in zip(pre, self.Ns)]
        return self._c[n]
    def A(self, h):
        th = self._theta(abs(h)); arg = TWO_PI_L * th
        cc = self._prefix(np.cos(arg)); ss = self._prefix(np.sin(arg)); sg = 1 if h > 0 else -1
        return [(cc[i] / N, sg * ss[i] / N) for i, N in enumerate(self.Ns)]
    mk = staticmethod(lambda v: LD(v))
    sqrt = staticmethod(lambda v: np.sqrt(v))

# ----------------------------------------------------------------------------- Source: rational x=p/q (exact residues, mpmath)
class RatSource:
    """x = p/q.  orbit residue r_j = p b^j mod q (EXACT).  Values via mpmath (dps = mp.mp.dps).
       Prefix sums over N use pre-period + period extrapolation (exact integer counting)."""
    def __init__(self, p, q, b, Ns, label):
        self.p, self.q, self.b, self.Ns, self.label = p % q, q, b, list(Ns), label
        seen = {}; r = self.p; j = 0; res = []
        while r not in seen:
            seen[r] = j; res.append(r); r = (r * b) % q; j += 1
        self.pre = seen[r]; self.P = j - self.pre; self.res = res
        self._cos = {}; self._c = {}
    def _terms(self, n):          # (cos,sin) for each stored orbit position
        out = []
        for r in self.res:
            k = (n * r) % self.q
            if k not in self._cos:
                ang = 2 * mp.pi * mp.mpf(k) / self.q
                self._cos[k] = (mp.cos(ang), mp.sin(ang))
            out.append(self._cos[k])
        return out
    def _prefix(self, vals, N):
        pre, P = self.pre, self.P
        pref = [mp.mpf(0)]
        for v in vals: pref.append(pref[-1] + v)
        if N <= pre + P: return pref[N]
        full, rem = divmod(N - pre, P)
        cyc = pref[pre + P] - pref[pre]
        return pref[pre] + full * cyc + (pref[pre + rem] - pref[pre])
    def c(self, n):
        if n not in self._c:
            vals = [t[0] for t in self._terms(n)]
            self._c[n] = [self._prefix(vals, N) / N for N in self.Ns]
        return self._c[n]
    def A(self, h):
        t = self._terms(abs(h)); sg = 1 if h > 0 else -1
        cs = [v[0] for v in t]; ss = [sg * v[1] for v in t]
        return [(self._prefix(cs, N) / N, self._prefix(ss, N) / N) for N in self.Ns]
    mk = staticmethod(lambda v: mp.mpf(v))
    sqrt = staticmethod(lambda v: mp.sqrt(v))

# ----------------------------------------------------------------------------- evaluation of all cells for one source
def evaluate(src, b, hlist, Rlist, want_all=True):
    """returns list of row dicts for (h,R,N) over the source's checkpoints."""
    rows = []
    Rmax = max(Rlist)
    for h in hlist:
        need = needed_set(b, h, Rmax)
        C = {m: src.c(m) for m in need}
        D = compute_D(C, need)
        Ah = src.A(h)
        for i, N in enumerate(src.Ns):
            absA = src.sqrt(Ah[i][0] ** 2 + Ah[i][1] ** 2)
            c1 = C[1][i]
            for R in Rlist:
                Dl = {d: D[abs(h) * (b ** d - 1)][i] for d in range(1, R)}
                t = terms(src.mk, src.sqrt, b, h, R, N, c1, Dl, absA)
                t.update(src=src.label, b=b, h=h, R=R, N=N)
                rows.append(t)
    return rows

# ----------------------------------------------------------------------------- pi bits
def pi_bits(nbits, guard=128):
    """bits of frac(pi) (nbits of them), computed at two precisions; asserts agreement."""
    out = []
    for g in (guard, guard + 300):
        with mp.workprec(nbits + g):
            M = int(mp.floor(mp.frac(mp.pi) * mp.mpf(2) ** nbits))
        out.append(M)
    assert out[0] == out[1], "pi bits disagree between precisions"
    return bits_from_int(out[0], nbits), out[0]

