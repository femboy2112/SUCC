"""Exact research adapters for source-faithful SUCC observation completion.

Not a replacement for observational_succ.operational_yoneda_descent.
No normality, RH, physical quantum, or finite-to-infinite cancellation claim.
All finite arithmetic is exact; rational coefficients come with a separately
verified integer-polynomial identity in polynomial_oracle.py.
"""
from __future__ import annotations
