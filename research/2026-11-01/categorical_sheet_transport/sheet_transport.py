class TransportError(ValueError):
    """An operation would lose required source, branch, or phase data."""

def integer(n: int, lower: int = 0) -> int:
    if type(n) is not int or n < lower:
        raise TransportError(f"integer >= {lower} required")
    return n

def rational(x: int | F) -> F:
    if type(x) not in (int, F):
        raise TransportError("exact int/Fraction required; floats and bools forbidden")
    return F(x)

def source(n: int) -> F:
    integer(n, 1)
    return 4/F(8*n-7) - 2/F(8*n-4) - 1/F(8*n-3) - 1/F(8*n-2)

def source_oracle(n: int) -> F:
    integer(n, 1)
    return F(120*n*n-89*n+16, (2*n-1)*(4*n-1)*(8*n-7)*(8*n-3))

def states(n: int, seed: int | F = F(0)) -> tuple[F, ...]:
    integer(n)
    out = [rational(seed)]
    for j in range(1, n+1):
        out.append(16*out[-1]+source(j))
    return tuple(out)

def authenticate(history: Sequence[F]) -> bool:
    if not history or rational(history[0]) != 0:
        raise TransportError("literal original U0=0 is required")
    for j, u in enumerate(history[1:], 1):
        if rational(u) != 16*rational(history[j-1])+source(j):
            raise TransportError(f"original source recurrence failed at {j}")
    return True

def conductor(n: int) -> int:
    integer(n, 1)
    return lcm(*(x.denominator for x in states(n)))

def R(z: int | F) -> F:
    z = rational(z)
    den = (8*z-4)**2*(8*z-3)*(8*z-2)
    if not den:
        raise TransportError("R has a projective infinity value here; change chart")
    return (8*z-7)**4/den

