def bivariate(terms: tuple, u: int | F, v: int | F) -> F:
    u, v = rational(u), rational(v)
    return sum((F(c)*u**i*v**j for i,j,c in terms), F(0))

def delay(z: int | F) -> tuple[F, F]:
    z = rational(z)
    return R(z), R(z+1)

def reconstruct(u: int | F, v: int | F) -> F:
    """The rational inverse on its proved chart; reject forged pairs.

    For every real z>=1 the denominator is strictly positive by the
    shifted-coefficient certificate. Exceptional complex points require
    the normalization chart; this routine never guesses a branch there.
    """
    u, v = rational(u), rational(v)
    if bivariate(CURVE_TERMS,u,v):
        raise TransportError("pair lies off the authenticated delay curve")
    a = bivariate(A_TERMS,u,v)
    if not a:
        raise TransportError("exceptional inverse chart; retain normalization label")
    z = -bivariate(B_TERMS,u,v)/(8*a)
    if delay(z) != (u,v):
        raise TransportError("pair is not reconstructed on the finite affine chart")
    return z

def delay_successor(u: int | F, v: int | F) -> tuple[F,F]:
    z = reconstruct(u,v)
    return rational(v), R(z+2)

@dataclass(frozen=True)
class SourceState:
    clock: int
    value: F
    seed: F = F(0)

    def __post_init__(self):
        integer(self.clock)
        object.__setattr__(self,'value',rational(self.value))
        object.__setattr__(self,'seed',rational(self.seed))
        if self.value != states(self.clock,self.seed)[-1]:
            raise TransportError("state is not on its declared original-source orbit")

    def successor(self) -> 'SourceState':
        return SourceState(self.clock+1,16*self.value+source(self.clock+1),self.seed)

    def selected(self) -> bool:
        return self.seed == 0

@dataclass(frozen=True)
class Mobius:
    a: F
    b: F
    c: F
    d: F

    def __post_init__(self):
        for name in ('a','b','c','d'):
            object.__setattr__(self,name,rational(getattr(self,name)))
        if not self.a*self.d-self.b*self.c:
            raise TransportError("singular projective frame")

    def __call__(self,z: F | int | None) -> F | None:
        if z is None:
            return self.a/self.c if self.c else None
        z=rational(z); den=self.c*z+self.d
        return (self.a*z+self.b)/den if den else None

    def compose(self,right:'Mobius')->'Mobius':
        return Mobius(self.a*right.a+self.b*right.c,
                      self.a*right.b+self.b*right.d,
                      self.c*right.a+self.d*right.c,
                      self.c*right.b+self.d*right.d)

    def inverse(self)->'Mobius':
        return Mobius(self.d,-self.b,-self.c,self.a)

    def equivalent(self,other:'Mobius')->bool:
        x=(self.a,self.b,self.c,self.d); y=(other.a,other.b,other.c,other.d)
        return all(x[i]*y[j]==x[j]*y[i] for i in range(4) for j in range(4))

    def conjugate(self,operation:'Mobius')->'Mobius':
        return self.compose(operation).compose(self.inverse())

IDENTITY=Mobius(1,0,0,1)
SUCCESSOR=Mobius(1,1,0,1)
