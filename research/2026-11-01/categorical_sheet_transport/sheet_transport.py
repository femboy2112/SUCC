def frame_change(source_frame:Mobius,target_frame:Mobius)->Mobius:
    return target_frame.compose(source_frame.inverse())

def _partition(values: Sequence[Hashable]) -> tuple[int,...]:
    ids={}; out=[]
    for x in values:
        if x not in ids: ids[x]=len(ids)
        out.append(ids[x])
    return tuple(out)

def complete_observer(transitions: Sequence[int], observations: Sequence[Hashable]) -> dict:
    """Coarsest successor-stable finite partition refining the observation.

    This is a small exact utility, not a new path-category implementation.
    Its universal property is proved in PROOFS.md. No infinite termination
    claim is made by this finite routine.
    """
    t=tuple(transitions); o=tuple(observations); size=len(t)
    if not size or size!=len(o) or size>10000:
        raise TransportError("nonempty finite machine of <=10000 states required")
    if any(type(x) is not int or not 0<=x<size for x in t):
        raise TransportError("transition is not a total map on the declared carrier")
    labels=_partition(o); history=[labels]
    while True:
        new=_partition(tuple((labels[x],labels[t[x]]) for x in range(size)))
        if new==labels: break
        labels=new;history.append(labels)
    reps=[labels.index(i) for i in range(max(labels)+1)]
    return {'labels':labels,'history':tuple(history),
            'successor':tuple(labels[t[x]] for x in reps),
            'observations':tuple(o[x] for x in reps)}

@dataclass(frozen=True)
class Monomial:
    """|x> -> exp(2pi i (b*x+c)/Q)|a*x+t>; exact central phase retained."""
    Q: int
    a: int=1
    t: int=0
    b: int=0
    c: int=0

    def __post_init__(self):
        integer(self.Q,3)
        if self.Q%2==0:
            raise TransportError("this source adapter requires an odd conductor")
        for name in ('a','t','b','c'):
            x=getattr(self,name)
            if type(x) is not int: raise TransportError("integer register labels required")
            object.__setattr__(self,name,x%self.Q)
        if gcd(self.a,self.Q)!=1:
            raise TransportError("wire map must be invertible; discarded branches forbidden")

    def apply(self,x:int)->tuple[int,int]:
        integer(x)
        return (self.a*x+self.t)%self.Q,(self.b*x+self.c)%self.Q

    def compose(self,right:'Monomial')->'Monomial':
        if self.Q!=right.Q: raise TransportError("different conductors need an explicit embedding")
        return Monomial(self.Q,self.a*right.a,self.a*right.t+self.t,
                        right.b+self.b*right.a,right.c+self.c+self.b*right.t)

    def inverse(self)->'Monomial':
        ai=pow(self.a,-1,self.Q)
        return Monomial(self.Q,ai,-ai*self.t,-self.b*ai,self.b*ai*self.t-self.c)

    def fourier(self)->'Monomial':
        """Exact F_+ O F_+^{-1}, with F_+(k,x)=e(kx/Q)/sqrt(Q)."""
        ai=pow(self.a,-1,self.Q)
        return Monomial(self.Q,ai,-ai*self.b,ai*self.t,self.c-ai*self.b*self.t)

    def embed(self,new_Q:int)->'Monomial':
        """Extension making O' I = I O for I|x>=|m*x>, Q'=mQ."""
        integer(new_Q,3)
        if new_Q%self.Q: raise TransportError("conductor divisibility required")
        m=new_Q//self.Q
        return Monomial(new_Q,self.a,m*self.t,self.b,m*self.c)


def source_operator(n:int,Q:int)->Monomial:
    integer(n,1)
    t=source(n)*Q
    if t.denominator!=1:
        raise TransportError("register does not carry the actual rational source")
    return Monomial(Q,16,int(t))

def propagator(n:int,Q:int)->Monomial:
    integer(n)
    p=Monomial(Q)
    for j in range(1,n+1): p=source_operator(j,Q).compose(p)
    return p

def phase_echo(n:int,h:int,Q:int)->Monomial:
    if type(h) is not int: raise TransportError("integer real-circle harmonic required")
    p=propagator(n,Q)
    return p.inverse().compose(Monomial(Q,b=h)).compose(p).compose(Monomial(Q,b=-h*16**n))

# Projective three-frame decoder. None denotes the point at infinity.
# Distinct finite points are separated by the exact Bezout certificate;
# infinity is separated by a second independent polynomial identity.
def projective_R(z: int | F | None) -> F | None:
    if z is None:
        return F(1)
    z=rational(z)
    den=(8*z-4)**2*(8*z-3)*(8*z-2)
    return (8*z-7)**4/den if den else None

def triple_delay(z: int | F | None) -> tuple:
    if z is None:
        return (F(1),F(1),F(1))
    z=rational(z)
    return tuple(projective_R(z+k) for k in range(3))

def _ptrim(p):
    p=list(map(F,p))
    while len(p)>1 and not p[-1]:p.pop()
    return tuple(p or [F(0)])

def _pmul(p,q):
    r=[F(0)]*(len(p)+len(q)-1)
    for i,a in enumerate(p):
        for j,b in enumerate(q):r[i+j]+=a*b
    return _ptrim(r)

def _prem(p,q):
    p=list(_ptrim(p));q=_ptrim(q)
    if q==(F(0),):raise TransportError('zero divisor polynomial')
    while len(p)>=len(q) and any(p):
        k=len(p)-len(q);c=p[-1]/q[-1]
        for j,b in enumerate(q):p[j+k]-=c*b
        p=list(_ptrim(p))
    return tuple(p)

def _pgcd(p,q):
    p,q=_ptrim(p),_ptrim(q)
    while any(q):p,q=q,_prem(p,q)
    return tuple(c/p[-1] for c in p) if any(p) else (F(0),)

def _source_polynomials(shift):
    # Directly multiply linear factors, independently of the inverse polynomials.
    a=(F(1),);d=(F(1),)
    for _ in range(4):a=_pmul(a,(8*shift-7,8))
    for c in (4,4,3,2):d=_pmul(d,(8*shift-c,8))
    return a,d

def reconstruct_triple(samples: Sequence[int | F | None]) -> F | None:
    """Exact decoder on P1(Q); proofs establish the complex geometric map.

    Common-root Euclid avoids assuming one globally valid affine inverse chart.
    Returns None for the unique infinity triple; rejects forged observations.
    """
    if len(samples)!=3:raise TransportError('exactly three ordered observations required')
    values=tuple(None if x is None else rational(x) for x in samples)
    if values==(F(1),F(1),F(1)):return None
    common=None
    for k,u in enumerate(values):
        a,d=_source_polynomials(k)
        eq=d if u is None else _ptrim(tuple(x-u*y for x,y in zip(a,d)))
        common=eq if common is None else _pgcd(common,eq)
    if len(common)!=2:
        raise TransportError('triple is off the source curve or violates unique-source decoding')
    z=-common[0]/common[1]
    if triple_delay(z)!=values:raise TransportError('decoded point does not authenticate the observations')
    return z

def triple_successor(samples: Sequence[int | F | None]) -> tuple:
    z=reconstruct_triple(samples)
    return triple_delay(None if z is None else z+1)
