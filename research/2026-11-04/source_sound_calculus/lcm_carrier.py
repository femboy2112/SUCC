from fractions import Fraction as F
from math import gcd, lcm

class CarrierError(ValueError):
    pass


def pos(n:int)->int:
    if type(n) is not int or n<1: raise CarrierError('positive exact integer required')
    return n


def divisor_join(a:int,b:int)->int:
    return lcm(pos(a),pos(b))


def phase_address(numerator:int,denominator:int,common:int)->int:
    """C_denominator -> C_common inclusion in Q/Z, compatible with addition."""
    m=pos(denominator); L=pos(common)
    if type(numerator) is not int or L % m: raise CarrierError('common clock must be a multiple')
    return ((numerator % m)*(L//m))%L


def phase_sum(a:int,m:int,b:int,n:int)->tuple[int,int]:
    L=divisor_join(m,n)
    return (phase_address(a,m,L)+phase_address(b,n,L))%L,L


@dataclass(frozen=True)
class CyclicJoinReceipt:
    a:int
    b:int
    gcd:int
    lcm:int
    kernel_size:int
    image_size:int
    source_size:int


def cyclic_join_finite(a:int,b:int,max_pairs:int=4096)->CyclicJoinReceipt:
    """Exhaustive *finite* kernel/image certificate for C_a + C_b -> C_lcm."""
    a=pos(a);b=pos(b)
    if a*b>max_pairs:raise CarrierError('exhaustive quotient budget exceeded')
    L=divisor_join(a,b)
    counts=[0]*L
    for x in range(a):
        for y in range(b):
            counts[(x*(L//a)+y*(L//b))%L]+=1
    g=gcd(a,b)
    if any(v!=g for v in counts):raise AssertionError('finite torsion join identity failed')
    return CyclicJoinReceipt(a,b,g,L,counts[0],sum(c!=0 for c in counts),a*b)


def force(n:int)->F:
    pos(n)
    p=120*n*n-89*n+16
    d=(2*n-1)*(4*n-1)*(8*n-7)*(8*n-3)
    return F(p,d)


def forcing_terms(n:int)->tuple[F,F,F,F]:
    pos(n)
    return (F(4,8*n-7), -F(2,8*n-4), -F(1,8*n-3), -F(1,8*n-2))


def reduced_force_pair(n:int)->tuple[int,int]:
    r=force(n)
    if r.denominator%2!=1: raise AssertionError('BBP source denominator must be odd')
    return r.numerator,r.denominator


@dataclass(frozen=True)
class BBPRegister:
    time:int
    clock:int
    numerator:int
    last_carry:int|None = None
    def __post_init__(self):
        if type(self.time) is not int or self.time<0 or pos(self.clock)%2!=1 or type(self.numerator) is not int:
            raise CarrierError('exact nonnegative original integer state, odd conductor required')
        if self.last_carry is not None and type(self.last_carry) is not int:
            raise CarrierError('literal carry must be integer')
    @property
    def unwrapped(self)->F:
        return F(self.numerator,self.clock)
    @property
    def phase(self)->F:
        return F(self.numerator % self.clock,self.clock)


def bbp_origin()->BBPRegister:
    return BBPRegister(0,1,0,None)


def bbp_step(prev:BBPRegister)->BBPRegister:
    if type(prev) is not BBPRegister: raise CarrierError('typed original BBP register required')
    n=prev.time+1
    a,b=reduced_force_pair(n)
    Q=divisor_join(prev.clock,b)
    c=(Q//b)*a
    lift=16*(Q//prev.clock)*prev.numerator+c
    literal_carry=(16*(Q//prev.clock)*(prev.numerator%prev.clock)+c)//Q
    return BBPRegister(n,Q,lift,literal_carry)


def bbp_prefix(N:int)->tuple[BBPRegister,...]:
    if type(N) is not int or N<0:raise CarrierError('nonnegative finite horizon')
    states=[bbp_origin()]
    for _ in range(N):states.append(bbp_step(states[-1]))
    return tuple(states)


def source_subgroup_clock(N:int)->int:
    """LCM of reduced r(j) denominators = minimal torsion subgroup generated by inputs."""
    if type(N) is not int or N<0: raise CarrierError('nonnegative finite horizon')
    L=1
    for i in range(1,N+1):L=divisor_join(L,force(i).denominator)
    return L


def local_phase_coordinates(address:int,clock:int,prime_powers:tuple[int,...])->tuple[int,...]:
    """Integer residues of x=a/clock in each p-primary Q/Z subgroup.

    For q=p^e|clock, the projection of x onto C_q is
    a * (clock/q)^(-1) mod q (as numerator over q), not a mod q.
    """
    clock=pos(clock)
    if type(address) is not int:raise CarrierError('integer address')
    if not prime_powers or lcm(*prime_powers)!=clock:
        # For pairwise coprime prime powers, product=lcm=clock.
        raise CarrierError('exact full prime-power decomposition required')
    if any(gcd(a,b)!=1 for i,a in enumerate(prime_powers) for b in prime_powers[i+1:]):
        raise CarrierError('CRT demands pairwise-coprime factors')
    return tuple(((address % clock)*pow(clock//q,-1,q))%q for q in prime_powers)


def global_from_local(components:tuple[int,...],prime_powers:tuple[int,...])->tuple[int,int]:
    if len(components)!=len(prime_powers) or not components:
        raise CarrierError('components mismatch')
    M=1
    for p in prime_powers:M*=pos(p)
    if len(prime_powers)>1 and any(gcd(a,b)!=1 for i,a in enumerate(prime_powers) for b in prime_powers[i+1:]):
        raise CarrierError('CRT not applicable to overlapping factors')
    a=0
    for k,q in zip(components,prime_powers):
        if type(k) is not int or not 0<=k<q:raise CarrierError('local component outside clock')
        # k/q embedded as numerator k*(M/q) mod M.
        a=(a+k*(M//q))%M
    return a,M


def prior_independence_countermodels()->dict:
    """Same C_6 LCM, distinct probability assignments on C_2 x C_3."""
    # local C2,C3 coordinates, exact probability by numerator/denominator
    uniform={tuple((i,j)):F(1,6) for i in range(2) for j in range(3)}
    point={(0,0):F(1)}
    correlated={(0,0):F(1,2),(1,1):F(1,2)}
    def independent(mu):
        px={i:sum((p for (a,b),p in mu.items() if a==i),F(0)) for i in range(2)}
        py={j:sum((p for (a,b),p in mu.items() if b==j),F(0)) for j in range(3)}
        return all(mu.get((i,j),F(0))==px[i]*py[j] for i in range(2) for j in range(3))
    return {'clock':6,'uniform_independent':independent(uniform),
            'zero_dirac_independent':independent(point),
            'correlated_prior_independent':independent(correlated)}
